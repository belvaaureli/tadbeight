    private void tmbEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tmbEditActionPerformed
        int baris = tblJadwal.getSelectedRow();

    if (baris == -1) {
        JOptionPane.showMessageDialog(this, "Pilih data dulu!");
        return;
    }

    int id = Integer.parseInt(tblJadwal.getValueAt(baris, 0).toString());
    String pengajar = tblJadwal.getValueAt(baris, 1).toString();
    String siswa = tblJadwal.getValueAt(baris, 2).toString();
    String hari = tblJadwal.getValueAt(baris, 3).toString();
    String jam = tblJadwal.getValueAt(baris, 4).toString();
    String ruangan = tblJadwal.getValueAt(baris, 5).toString();

    new formjadwal(
    email,
    id,
    pengajar,
    siswa,
    hari,
    jam,
    ruangan
).setVisible(true);
    this.dispose();
    }//GEN-LAST:event_tmbEditActionPerformed

    private void tmbHapusActionPerformed(java.awt.event.ActionEvent evt) {
    if (email != null && email.contains("siswa")) {
    JOptionPane.showMessageDialog(this, "Siswa tidak punya akses!");
    return;
}
        
        int baris = tblJadwal.getSelectedRow();

    if (baris == -1) {
        JOptionPane.showMessageDialog(this, "Pilih data dulu!");
        return;
    }

    int konfirmasi = JOptionPane.showConfirmDialog(this, "Yakin mau hapus?", "Konfirmasi", JOptionPane.YES_NO_OPTION);

    if (konfirmasi == JOptionPane.YES_OPTION) {
        try {
            int id = Integer.parseInt(tblJadwal.getValueAt(baris, 0).toString());

            Connection conn = Koneksi.getConnection();
            String sql = "DELETE FROM jadwal WHERE id_jadwal=?";
            java.sql.PreparedStatement pst = conn.prepareStatement(sql);
            pst.setInt(1, id);
            pst.executeUpdate();

            JOptionPane.showMessageDialog(this, "Data berhasil dihapus!");

            loadData(); // refresh tabel

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }
}
