    private void loadData() {
    try {
        Connection conn = Koneksi.getConnection();

       String sql = "SELECT j.id_jadwal, " +
             "p.nama_pengajar AS pengajar, " +
             "s.nama AS siswa, " +
             "r.nama_ruangan, " +
             "j.hari, j.jam " +
             "FROM jadwal j " +
             "JOIN pengajar p ON j.id_pengajar = p.id_pengajar " +
             "JOIN siswa s ON j.id_siswa = s.id_siswa " +
             "JOIN ruangan r ON j.id_ruangan = r.id_ruangan";

        ResultSet rs = conn.createStatement().executeQuery(sql);

        DefaultTableModel model = (DefaultTableModel) tblJadwal.getModel();
        model.setRowCount(0);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("id_jadwal"),
                rs.getString("pengajar"),
                rs.getString("siswa"),
                rs.getString("hari"),
                rs.getString("jam"),
                rs.getString("nama_ruangan")
            });
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
}

