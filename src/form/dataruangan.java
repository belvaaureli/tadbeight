    private void tmbHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tmbHapusActionPerformed
         int baris = tblRuangan.getSelectedRow();

    if (baris == -1) {
        JOptionPane.showMessageDialog(this, "Pilih data dulu!");
        return;
    }

    int id = Integer.parseInt(tblRuangan.getValueAt(baris, 0).toString());

    try {
        Connection conn = Koneksi.getConnection();
        String sql = "DELETE FROM ruangan WHERE id_ruangan=?";
        PreparedStatement pst = conn.prepareStatement(sql);

        pst.setInt(1, id);
        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Data berhasil dihapus!");
        loadData();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    }//GEN-LAST:event_tmbHapusActionPerformed

