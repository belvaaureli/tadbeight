    private void loadData() {
    try {
        Connection conn = Koneksi.getConnection();
        ResultSet rs = conn.createStatement().executeQuery("SELECT * FROM ruangan");

        DefaultTableModel model = (DefaultTableModel) tblRuangan.getModel();
        model.setRowCount(0);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("id_ruangan"),
                rs.getString("nama_ruangan"),
                rs.getInt("kapasitas")
            });
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
}

